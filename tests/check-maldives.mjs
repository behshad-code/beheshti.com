import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import vm from 'node:vm';
const read = p => readFileSync(p, 'utf8');
const html = read('journeys/maldives-ithaafushi/index.html');
const app = read('app.js');
const sitemap = read('sitemap.xml');
const galleryJS = read('maldives-gallery.js');
const css = read('maldives-feature.css');
assert(html.includes('href="/maldives-feature.css"'), 'Feature CSS missing');
assert(app.includes('class="bh-featured-lead"') && app.includes('href="${routeLink(m.id)}"'), 'Maldives must remain directly discoverable on the homepage');
assert(app.includes('bh-table-feature') && app.includes('href="${tidy(d.href)}"'), 'Dining chapters must remain accessible from homepage');
assert(app.indexOf('bh-featured-lead') < app.indexOf('bh-table-feature'), 'Featured Maldives story must appear before the Food & Wine chapter section');
assert(html.includes('private-yacht transfer took about 45 minutes') && html.includes('caviar and snacks'), 'Anniversary arrival details missing');
assert(html.includes('Lebanese and Middle Eastern food to the beach'), 'First-night beach dinner missing');
assert(app.includes('new Set(C.destinations.map(d=>d.country).sort())'), 'Journeys country filters are not derived from destinations');
assert(html.includes('src="/maldives-gallery.js"'), 'Gallery script missing');
assert(css.includes('prefers-reduced-motion'), 'Reduced-motion support missing');
assert(galleryJS.includes('ArrowRight') && galleryJS.includes('ArrowLeft'), 'Keyboard gallery navigation missing');
assert(app.includes("id==='maldives-ithaafushi'?'/journeys/maldives-ithaafushi/'"), 'Story routing missing');
assert(sitemap.includes('https://beheshti.com/journeys/maldives-ithaafushi/'), 'Sitemap missing story URL');
const sandbox = { window: {} };
vm.runInNewContext(read('content.js'), sandbox, { filename: 'content.js' });
const content = sandbox.window.BEHESHTI_CONTENT;
assert.equal(content.stories.filter(s => s.id === 'maldives-ithaafushi').length, 1, 'Duplicate or missing story entry');
assert.equal(content.destinations.filter(s => s.id === 'maldives').length, 1, 'Duplicate or missing destination entry');
const imageDir = 'images/maldives';
const files = readdirSync(imageDir).filter(x => x.endsWith('.webp')).sort();
assert.equal(files.length, 128, 'Expected exactly 128 image derivatives');
assert.equal(files.filter(x => x.endsWith('-sm.webp')).length, 64, 'Expected 64 small derivatives');
for (const filename of files) {
  const path = `${imageDir}/${filename}`;
  const buf = readFileSync(path);
  assert.equal(buf.toString('ascii', 0, 4), 'RIFF', `Not RIFF: ${path}`);
  assert.equal(buf.toString('ascii', 8, 12), 'WEBP', `Not WebP: ${path}`);
  assert(statSync(path).size < 1800000, `Unusually large public image: ${path}`);
  assert.equal(buf.readUInt32LE(4) + 8, buf.length, `WebP RIFF length mismatch: ${path}`);
  for (let o = 12; o + 8 <= buf.length;) {
    const chunk = buf.toString('ascii', o, o + 4);
    const size = buf.readUInt32LE(o + 4);
    assert(!['EXIF', 'XMP ', 'ICCP'].includes(chunk), `Private metadata in ${path}`);
    o += 8 + size + (size % 2);
  }
}
const refs = [...html.matchAll(/\/images\/maldives\/([a-z0-9-]+\.webp)/g)].map(m => m[1]);
assert(refs.length > 100, 'Not enough article image references');
for (const filename of new Set(refs)) assert(existsSync(`${imageDir}/${filename}`), `Broken image: ${filename}`);
const chapterIds = ['the-arrival','beach-dinner','our-villa','at-the-table','island-life','private-island','villa-dinner','li-long','zuma','the-simple-things','sandbars','the-sunset','until-next-time'];
for (const id of chapterIds) assert(html.includes(`id="${id}"`), `Missing chapter: ${id}`);
const lightboxes = [...html.matchAll(/data-mdv-lightbox="([^"]+)"/g)].map(m => m[1]);
assert.equal(lightboxes.length, 63, 'Expected 63 gallery photographs');
assert.equal(new Set(lightboxes).size, lightboxes.length, 'Duplicate gallery photographs');
assert(html.includes('<link rel="canonical" href="https://beheshti.com/journeys/maldives-ithaafushi/"'), 'Incorrect canonical URL');
assert(html.includes('<h1 class="mdv-editorial-title">Somewhere <br>Between Sea <br><em>and Sky</em></h1>'), 'Maldives headline inconsistent with approved title');
assert(html.includes('<meta property="og:title" content="Somewhere Between Sea and Sky | BEHESHTI">'), 'Open Graph headline not updated');
assert(html.includes('<meta name="twitter:title" content="Somewhere Between Sea and Sky | BEHESHTI">'), 'Twitter headline not updated');
assert(html.includes('<title>Somewhere Between Sea and Sky | Maldives | BEHESHTI</title>'), 'Browser page title not updated');
assert(html.includes('"headline":"Somewhere Between Sea and Sky"'), 'Structured data headline not updated');
assert(!html.includes('Seven Nights, Never Enough'), 'Old feature title remains in public page metadata');
assert(html.includes('<section class="mdv-hero" aria-label="The Maldives"><img src="/images/maldives/private-island-pool.webp"'), 'Hero must show the private island pool photograph');
assert(html.includes('https://beheshti.com/images/maldives/private-island-pool.webp'), 'Social preview not updated');
assert(html.includes('visited during our stay'), 'Private island tour must not be implied to be an overnight stay');
assert(html.includes('<a href="#beach-dinner">First Night</a>'), 'First-night dining chapter missing from navigation');
assert(html.includes('<section class="mdv-chapter" id="beach-dinner"'), 'Lebanese dinner must be an independent chapter');
assert(html.includes('Lebanese and Middle Eastern food to the beach'), 'First-night Lebanese dinner prose missing');
assert(html.includes('crisp fried kibbeh') && html.includes('parsley-rich salad') && html.includes('slow-cooked meat and nuts'), 'Original photograph-supported dinner details missing');
assert(html.includes('number 702'), 'Villa 702 detail missing');
assert(html.includes('data-mdv-lightbox="evening-pier"') && html.includes('data-mdv-lightbox="palm-and-pavilion"'), 'Unpublished atmospheric photos have not been integrated');
assert(html.includes('data-mdv-lightbox="quiet-lagoon"'), 'Original hero photo must remain in the article');
assert(!lightboxes.includes('private-island-pool'), 'Hero photo should not be repeated in the gallery');
const allFull = files.filter(x=>!x.endsWith('-sm.webp'));
const displayedFull = new Set([...html.matchAll(/\/images\/maldives\/([a-z0-9-]+\.webp)/g)].map(x=>x[1]).filter(x=>!x.endsWith('-sm.webp')));
assert.deepEqual([...displayedFull].sort(), allFull, 'Every curated full-size image must be represented in the story exactly once across hero and gallery');

console.log(`PASS: ${chapterIds.length} chapters, ${lightboxes.length} gallery photographs, ${files.length} metadata-free images, and integrated navigation.`);